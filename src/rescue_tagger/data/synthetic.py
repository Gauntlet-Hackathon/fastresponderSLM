@dataclass
class Spec:
    """The labels a synthetic message must express. Serialized into meta.spec."""

    seed: int
    lang: str
    style: str
    is_request: bool
    non_request_type: str | None
    is_stale_post: bool
    request_kind: str
    hazards: list[str] = field(default_factory=list)
    vulnerable: list[str] = field(default_factory=list)
    vulnerable_indirect: bool = False
    needs: dict[str, float | None] = field(default_factory=dict)
    location_type: str = "address"
    location_hint: str | None = None
    people_count: int | None = None
    count_style: str = "digits"
    time_ref: bool = False
    contact: bool = False
    prompt_injection: bool = False
    shared_duration: bool = False   # one stated duration covers every need
    device: str | None = None       # the powered device, for medical_device_no_power
    vague: bool = False             # too vague to call: is_request is a soft 0.5, never scored
    hoax: bool = False              # reads like a request but may be a prank: soft 0.5 as well
    third_party: bool = False       # written about someone else who is not with the writer
    hazard_implied: bool = False    # hazards implied by the situation, never named


# Powered medical devices (rubric: "a medical device that needs electricity").
DEVICES = ("a home oxygen concentrator", "a CPAP machine", "a home dialysis machine",
           "a ventilator", "a powered wheelchair that needs charging", "a nebulizer",
           "an electric feeding pump", "a suction machine")
# Old posts name one of these, never Harvey: the Harvey hold-out is Harvey tweets, and "Harvey
# means old post" is a shortcut (data/synthetic/fix_v3.py fixed the earlier batches).
PAST_STORMS = ("Hurricane Ike in 2008", "Tropical Storm Allison in 2001",
               "Tropical Storm Imelda in 2019", "Hurricane Beryl in 2024", "Hurricane Rita in 2005",
               "the Memorial Day flood of 2015", "a past year such as 2016")
FOCUS = ("medical_device", "shared_duration", "stale", "indirect_vulnerable")
# v6 (b0008+): weights move toward the categories with the fewest training rows after v5; shared
# durations were the best covered. Categories and weights only, never text from any eval set.
FOCUS_WEIGHTS = (30, 15, 20, 35)
# Vietnamese since v6: the product needs it to work as well as English, and no public source has it.
SYNTH_LANG_WEIGHTS = (45, 25, 15, 15)


def sample_focus_spec(seed: int) -> Spec:
    """A request built around one under-covered category (see --focus). Deterministic per seed;
    the base spec supplies language, style, location and the rest."""
    r = random.Random(f"focus:{seed}")
    spec = sample_spec(seed)
    focus = r.choices(FOCUS, weights=FOCUS_WEIGHTS)[0]
    if not spec.is_request:
        spec.is_request, spec.non_request_type = True, None
        spec.request_kind = r.choices(L.REQUEST_KINDS, weights=(40, 20, 10, 25, 5))[0]
    spec.is_stale_post = focus == "stale"
    spec.time_ref = spec.time_ref or spec.is_stale_post
    if spec.people_count is None and r.random() < 0.6:
        spec.people_count = r.choices([1, 2, 3, 4, 5, 6, 7, 9], weights=(10, 25, 20, 15, 10,
                                                                         8, 6, 6))[0]
    if spec.people_count is not None:
        spec.count_style = r.choice(["words", "words", "digits",
                                     "implied by a phrase like 'me and my 2 kids'"])
    if focus == "medical_device":
        spec.device = r.choice(DEVICES)
        spec.hazards = sorted(set(spec.hazards) | {"medical_device_no_power"})
        # Depending on a powered device is dependence on treatment: the rubric's "medical".
        spec.vulnerable = sorted(set(spec.vulnerable) | {"medical"})
        if spec.request_kind == "other":
            spec.request_kind = r.choice(["evacuation", "rescue"])
        if "wheelchair" in spec.device:  # a powered wheelchair also means a mobility disability
            spec.vulnerable = sorted(set(spec.vulnerable) | {"disabled"})
    elif focus == "shared_duration":
        kinds = r.sample(list(L.NEED_KINDS), r.choice([2, 2, 3]))
        hours = r.choice([8, 12, 24, 36, 48, 72])
        spec.needs = {k: hours for k in kinds}
        spec.shared_duration = True
        spec.request_kind = r.choice(["supply", "supply", "rescue", "evacuation"])
    elif focus == "indirect_vulnerable":
        spec.vulnerable = r.sample(list(L.VULNERABLE_KINDS), r.choice([1, 1, 2]))
        spec.vulnerable_indirect = True
    if "medical_device_no_power" in spec.hazards:  # the rubric, for base specs too
        spec.vulnerable = sorted(set(spec.vulnerable) | {"medical"})
    if spec.request_kind == "supply" and not spec.needs:
        spec.needs = {r.choice(L.NEED_KINDS): r.choice([None, 24, 48])}
    spec.vulnerable = [v for v in L.VULNERABLE_KINDS if v in spec.vulnerable]
    spec.hazards = [h for h in L.HAZARD_KINDS if h in spec.hazards]
    return spec


def sample_vague_spec(seed: int) -> Spec:
    """A message too vague to tell whether the sender needs help (rubric: the right answer is low
    confidence, not a guess). It states no hazard, vulnerable person, need or count, so those heads
    are cleanly labeled as absent; is_request gets a soft 0.5 target (records.soft_labels)."""
    spec = sample_spec(seed)
    spec.is_request, spec.non_request_type, spec.request_kind = True, None, "other"
    spec.is_stale_post, spec.hazards, spec.vulnerable, spec.needs = False, [], [], {}
    spec.vulnerable_indirect, spec.people_count, spec.prompt_injection = False, None, False
    spec.contact = False
    if spec.location_type == "coords":
        spec.location_type, spec.location_hint = "none", None
    spec.vague = True
    return spec


HOAX_SIGNS = (
    "an impossible or absurd detail (a shark in the living room, a pet dinosaur)",
    "'lol', 'jk' or laughing emojis next to the plea",
    "meme or copypasta phrasing",
    "a friend tagging someone else as a joke ('come rescue @dave from his cooking')",
    "a celebrity or fictional character named as the person in danger",
    "an over-the-top tone that might be sarcasm",
)


def sample_hoax_spec(seed: int) -> Spec:
    """A message that reads like a rescue request but carries signs it may be a prank (rubric:
    pranks and unclear posts get low is_request confidence, never a confident yes). The stated
    details (place, people, hazards) are labeled as written; is_request is a soft 0.5."""
    r = random.Random(f"hoax:{seed}")
    spec = sample_spec(seed)
    spec.is_request, spec.non_request_type, spec.is_stale_post = True, None, False
    spec.prompt_injection, spec.vague = False, False
    spec.hoax = True
    spec.style = f"{spec.style}; hoax sign: {r.choice(HOAX_SIGNS)}"
    return spec


# --mix (v8, b0010+): Paawan asked (2026-11-07) for more mixed-language messages, old posts and
# requests made on someone else's behalf. Categories and weights only, never text from any eval set.
MIX = ("code_switch", "stale", "third_party")
MIX_WEIGHTS = (35, 30, 35)
CODE_SWITCH = {
    "mixed": "switches between English and Spanish mid-sentence, the way bilingual "
             "Houstonians text",
    "vi": "switches between Vietnamese and English mid-sentence (English words for places, "
          "agencies and some phrases)",
}


def sample_mix_spec(seed: int) -> Spec:
    """A request built around code-switching, an old post or a third-party ask (see --mix).
    Deterministic per seed; the base spec supplies style, location and the rest."""
    r = random.Random(f"mix:{seed}")
    spec = sample_spec(seed)
    focus = r.choices(MIX, weights=MIX_WEIGHTS)[0]
    if not spec.is_request:
        spec.is_request, spec.non_request_type = True, None
        spec.request_kind = r.choices(L.REQUEST_KINDS, weights=(40, 20, 10, 25, 5))[0]
    spec.prompt_injection = False
    if focus == "code_switch" or r.random() < 0.3:  # mixed language within the other two as well
        spec.lang = r.choice(["mixed", "mixed", "vi"])
        spec.style = f"{spec.style}; {CODE_SWITCH[spec.lang]}"
    spec.is_stale_post = focus == "stale"
    spec.time_ref = spec.time_ref or spec.is_stale_post
    if focus == "third_party":
        spec.third_party = True
        spec.request_kind = r.choices(["rescue", "evacuation", "welfare_check", "supply"],
                                      weights=(35, 25, 30, 10))[0]
        who = r.choice(["a relative", "a neighbor", "a friend", "a coworker", "an adult child"])
        spec.style = (f"{spec.style}; written by {who} about someone else who is NOT with the "
                      "writer (third person: they/her/him, their address, their situation)")
    if "medical_device_no_power" in spec.hazards:  # the rubric, for base specs too
        spec.vulnerable = sorted(set(spec.vulnerable) | {"medical"})
    if spec.request_kind == "supply" and not spec.needs:
        spec.needs = {r.choice(L.NEED_KINDS): r.choice([None, 24, 48])}
    spec.vulnerable = [v for v in L.VULNERABLE_KINDS if v in spec.vulnerable]
    spec.hazards = [h for h in L.HAZARD_KINDS if h in spec.hazards]
    return spec


