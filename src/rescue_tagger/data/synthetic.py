def _is_vague(rec: dict[str, Any]) -> bool:
    return "is_request" in rec.get("soft_labels", {})


def _verify_call(client, rec: dict[str, Any], verify_model: str) -> dict[str, Any]:
    if _is_vague(rec):
        return _call_json(client, verify_model, VAGUE_VERIFY_SYSTEM, rec["text"],
                          VAGUE_VERIFY_SCHEMA, "labels")
    return _call_json(client, verify_model, VERIFY_SYSTEM, rec["text"], VERIFY_SCHEMA, "labels")


def find_span(text: str, quote: str | None, label: str,
              taken: list[dict[str, Any]] | None = None) -> dict[str, Any] | None:
    """First exact match of `quote` not overlapping `taken`; None if no quote; raises if the
    quote is missing from the text."""
    if not quote:
        return None
    quote = quote.strip()
    taken = taken or []
    start = text.find(quote)
    if start < 0:
        raise ValueError(f"{label} quote not found in text: {quote!r}")
    first = start
    while start >= 0:
        end = start + len(quote)
        if not any(start < t["end"] and t["start"] < end for t in taken):
            return {"start": start, "end": end, "label": label}
        start = text.find(quote, start + 1)
    return {"start": first, "end": first + len(quote), "label": label}  # overlap -> rejected


def _remove_overlaps(spans: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for s in sorted(spans, key=lambda s: (s["start"], -(s["end"] - s["start"]))):
        if out and s["start"] < out[-1]["end"]:
            raise ValueError(f"overlapping spans {out[-1]} and {s}")
        out.append(s)
    return out


def build_record(spec: Spec, gen: dict[str, Any], model: str) -> dict[str, Any]:
    """Turn a spec + generator output into a validated record. Raises ValueError if inconsistent."""
    text = gen["text"].strip()
    spans: list[dict[str, Any]] = []
    # Longest quotes first, each at its first occurrence that does not overlap one already placed,
    # so a COUNT "3" is not found inside the address "3810 Navigation Blvd".
    quotes = [(gen.get(lab), lab) for lab in ("LOCATION", "COUNT", "TIME", "CONTACT")]
    quotes += [(gen["NEED_DURATION"].get(k), "NEED_DURATION") for k in L.NEED_KINDS]
    for quote, label in sorted(quotes, key=lambda q: -len(q[0] or "")):
        sp = find_span(text, quote, label, taken=spans)
        if sp is not None and not any(sp == t for t in spans):
            spans.append(sp)
    spans = _remove_overlaps(spans)
    has = {s["label"] for s in spans}
    if (spec.location_type == "none") == ("LOCATION" in has):
        raise ValueError("location presence does not match spec")
    if spec.people_count is not None and "COUNT" not in has:
        raise ValueError("count requested but no COUNT span")

    loc_span = next((s for s in spans if s["label"] == "LOCATION"), None)
    time_span = next((s for s in spans if s["label"] == "TIME"), None)
    loc_text = text[loc_span["start"]:loc_span["end"]] if loc_span else None
    gold = {
        "location": {"text": loc_text, "type": spec.location_type, "confidence": 1.0},
        "people_count": {"value": spec.people_count, "confidence": 1.0},
        "vulnerable": [{"kind": v, "confidence": 1.0} for v in spec.vulnerable],
        "hazards": [{"kind": h, "confidence": 1.0} for h in spec.hazards],
        "time_ref": {
            "text": text[time_span["start"]:time_span["end"]] if time_span else None,
            "is_stale_post": spec.is_stale_post,
            "confidence": 1.0,
        },
        "is_request": {"value": spec.is_request, "confidence": 1.0},
        "spans": [s for s in spans if s["label"] != "CONTACT"],
        "needs": [{"kind": k, "hours_without": h} for k, h in spec.needs.items()],
        "request_kind": spec.request_kind,
    }
    rec = {
        "id": f"synthetic:{model.rsplit('/', 1)[-1]}:{spec.seed}",
        "source": "synthetic",
        "lang": spec.lang,
        "text": text,
        "split": "train",  # assigned for real by the build step (fixed, hash-based)
        "labels": {
            "is_request": spec.is_request,
            "is_stale_post": spec.is_stale_post,
            "request_kind": spec.request_kind,
            "location_type": spec.location_type,
            "vulnerable": {k: k in spec.vulnerable for k in L.VULNERABLE_KINDS},
            "hazards": {k: k in spec.hazards for k in L.HAZARD_KINDS},
            "needs": {k: k in spec.needs for k in L.NEED_KINDS},
        },
        "spans": spans,
        "people_count": spec.people_count,
        "need_hours": dict(spec.needs),
        "gold_extracted": gold,
        "meta": {"generator": model, "spec": asdict(spec)},
    }
    if spec.vague or spec.hoax:
        del rec["labels"]["is_request"], rec["labels"]["request_kind"]
        rec["soft_labels"] = {"is_request": 0.5}
        gold["is_request"] = {"value": True, "confidence": 0.5}  # p = 0.5 reads as True
    validate_record(rec)
    return rec


def disagreements(rec: dict[str, Any], v: dict[str, Any]) -> list[str]:
    """Heads where the blind verifier disagrees with the spec labels."""
    return [msg for _, msg in _diffs(rec, v)]


def _diffs(rec: dict[str, Any], v: dict[str, Any]) -> list[tuple[str, str]]:
    lab = rec["labels"]
    out = []
    for head in ("is_request", "is_stale_post", "request_kind", "location_type"):
        if head in lab and lab[head] != v[head]:  # a vague row has no is_request / request_kind
            out.append((head, f"{head}: spec={lab[head]} verify={v[head]}"))
    for head in ("hazards", "vulnerable", "needs"):
        if head not in lab:
            continue
        want = {k for k, on in lab[head].items() if on}
        if want != set(v[head]):
            out.append((head, f"{head}: spec={sorted(want)} verify={sorted(v[head])}"))
    if "people_count" in rec and rec["people_count"] != v["people_count"]:
        out.append(("people_count",
                    f"people_count: spec={rec['people_count']} verify={v['people_count']}"))
    return out


# A row whose text the verifier reads differently on a few fields is still good text: those fields
# become unknown (masked from the loss, never guessed), as with the edge cases' second labeler.
# Disagreeing on whether it is a request at all, or on many fields, means the text is off-spec.
MAX_MASKED = 2
SPAN_OF_HEAD = {"people_count": "COUNT", "needs": "NEED_DURATION"}


def apply_verdict(rec: dict[str, Any], v: dict[str, Any], verify_model: str
                  ) -> dict[str, Any]:
    """{"record": rec} (disagreeing heads masked) or {"seed", "error", "text"} if rejected."""
    seed = rec["meta"]["spec"]["seed"]
    diffs = _diffs(rec, v)
    heads = [h for h, _ in diffs]
    rec["meta"]["verifier"] = verify_model
    hoax = rec["meta"]["spec"].get("hoax")
    # A possible prank may read as "no help" (it is a joke) or "cannot tell", never as a real plea.
    allowed = ("cannot_tell", "no_help") if hoax else ("cannot_tell",)
    if _is_vague(rec) and v.get("help") not in allowed:
        kind = "hoax" if hoax else "vague"
        return {"seed": seed, "error": f"verify: {kind} row read as help={v.get('help')}",
                "text": rec["text"]}
    if "is_request" in heads or len(heads) > MAX_MASKED:
        return {"seed": seed, "error": "verify: " + "; ".join(m for _, m in diffs),
                "text": rec["text"]}
    if heads:
        for h in heads:
            if h == "people_count":
                del rec["people_count"]
            else:
                del rec["labels"][h]
                if h == "needs":
                    rec.pop("need_hours", None)
        # A masked count or need must not still be taught through its span: the BIO head reads
        # spans, and dropping just those spans would teach "O" on the words. Spans become unknown.
        disputed = {SPAN_OF_HEAD[h] for h in heads if h in SPAN_OF_HEAD}
        if rec.get("spans") and any(sp["label"] in disputed for sp in rec["spans"]):
            rec["spans"] = None
        rec["meta"]["masked"] = {h: m for h, m in diffs}
        rec.pop("gold_extracted", None)  # no longer matches the labels (few-shots skip it)
        validate_record(rec)
    return {"record": rec}


def _client():
    from openai import OpenAI

    key = os.environ.get("OPENAI_SLM_API_KEY") or os.environ.get("OPENAI_API_KEY")
    if not key:
        raise SystemExit("Set OPENAI_SLM_API_KEY or OPENAI_API_KEY")
    # Explicit, so local vLLM traffic (modal_jobs/synth.py) can never fall through to OpenAI.
    return OpenAI(api_key=key, base_url=os.environ.get("OPENAI_BASE_URL") or None)


def _call_json(client, model: str, system: str, user: str, schema: dict, name: str) -> dict:
    resp = client.chat.completions.create(
        model=model,
        messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
        response_format={"type": "json_schema",
                         "json_schema": {"name": name, "schema": schema, "strict": True}},
        # Local vLLM only (OpenAI reasoning models reject max_tokens): a looping constrained
        # decode is cut off and rejected instead of running to the context limit.
        **({"max_tokens": 1500} if os.environ.get("OPENAI_BASE_URL") else {}),
    )
    return json.loads(resp.choices[0].message.content)


def generate_one(client, seed: int, gen_model: str, verify_model: str | None,
                 focus: bool = False, vague: bool = False, hoax: bool = False,
                 mix: bool = False, implied: bool = False) -> dict[str, Any]:
    """Returns {"record": ...} on success or {"seed", "error"} when the row is rejected."""
    spec = (sample_hoax_spec(seed) if hoax else sample_vague_spec(seed) if vague
            else sample_mix_spec(seed) if mix else sample_implied_spec(seed) if implied
            else sample_focus_spec(seed) if focus else sample_spec(seed))
    try:
        gen = _call_json(client, gen_model, GEN_SYSTEM, build_prompt(spec), GEN_SCHEMA, "message")
        rec = build_record(spec, gen, gen_model)
        if verify_model:
            return apply_verdict(rec, _verify_call(client, rec, verify_model), verify_model)
        return {"record": rec}
    except Exception as e:  # noqa: BLE001 - every failure is a rejected row, logged with its seed
        return {"seed": seed, "error": f"{type(e).__name__}: {e}"}


def verify_record(client, rec: dict[str, Any], verify_model: str) -> dict[str, Any]:
    try:
        v = _verify_call(client, rec, verify_model)
    except Exception as e:  # noqa: BLE001 - a failed check is a rejected row
        return {"seed": rec["meta"]["spec"]["seed"], "error": f"{type(e).__name__}: {e}"}
    return apply_verdict(rec, v, verify_model)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--n", type=int, default=0, help="number of specs to try")
    ap.add_argument("--seed", type=int, default=0, help="first seed; seeds are seed..seed+n-1")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--gen-model", default=DEFAULT_GEN_MODEL)
    ap.add_argument("--verify-model", default=DEFAULT_VERIFY_MODEL,
                    help="blind labeler; pass '' to skip verification")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--focus", action="store_true",
                    help="sample the under-covered categories (see the module docstring)")
    ap.add_argument("--vague", action="store_true",
                    help="messages too vague to call (soft is_request 0.5; see sample_vague_spec)")
    ap.add_argument("--hoax", action="store_true",
                    help="requests that may be pranks (soft is_request 0.5; see sample_hoax_spec)")
    ap.add_argument("--mix", action="store_true",
                    help="code-switching, old posts and third-party asks (see sample_mix_spec)")
    ap.add_argument("--implied", action="store_true",
                    help="P1 hazards implied, not named, in messy typing (see sample_implied_spec)")
    ap.add_argument("--verify-file", type=Path, default=None,
                    help="only check the records in this file with --verify-model")
    args = ap.parse_args(argv)

    if not args.verify_file and args.n <= 0:
        ap.error("give --n (specs to generate) or --verify-file")
    client = _client()
    with ThreadPoolExecutor(args.workers) as pool:
        if args.verify_file:
            recs = [json.loads(ln) for ln in args.verify_file.read_text().splitlines()
                    if ln.strip()]
            results = list(pool.map(lambda r: verify_record(client, r, args.verify_model),
                                    recs))
        else:
            seeds = range(args.seed, args.seed + args.n)
            results = list(pool.map(
                lambda s: generate_one(client, s, args.gen_model, args.verify_model or None,
                                       args.focus, args.vague, args.hoax, args.mix,
                                       args.implied), seeds))
    kept = [r["record"] for r in results if "record" in r]
    rejected = [r for r in results if "record" not in r]
    write_jsonl(args.out, kept)
    write_jsonl(args.out.with_suffix(".rejected.jsonl"), rejected)
    print(f"kept {len(kept)}/{len(results)}, rejected {len(rejected)} -> {args.out}",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
