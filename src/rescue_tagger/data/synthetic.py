"""Synthetic English / Spanish / mixed / Vietnamese Houston rescue requests, generated label-first.

Why label-first: we sample the labels (a "spec") with a seeded RNG, then ask an LLM to write a
message that expresses exactly that spec and to quote the exact substrings for each span. The
labels therefore come from the spec, not from the LLM's reading of its own text. A second, blind
pass (`--verify`) has a different model label the text from scratch; rows where the two disagree on
any head are dropped, which catches messages that drifted from their spec.

Model family rule (brief, data rule 3): training data is never generated by Claude models (OpenAI
models, and since 2026-11-07 open-weights models served on Modal), so that golden set B and the
edge cases can be drafted by a different family (Claude) and checked by a person.

Open-weights models run behind vLLM's OpenAI-compatible server (modal_jobs/synth.py): set
OPENAI_BASE_URL and generate with --verify-model '' first, then check the file with --verify-file
using a different model family, since one server holds one model.

Usage:
  python -m rescue_tagger.data.synthetic --n 200 --seed 1 --out data/synthetic/batches/b001.jsonl
  python -m rescue_tagger.data.synthetic --focus --n 700 --seed 300000 --out .../b0003-focus.jsonl

--focus samples the categories the earlier batches barely cover (counted from the training data,
never from any eval set): powered medical devices without power (10 of 1,706 rows, and none also
labeled medical although the rubric counts dependence on treatment as medical), one duration that
covers several needs (14 rows), old posts (76) and vulnerable people described indirectly.
Needs OPENAI_SLM_API_KEY (or OPENAI_API_KEY).
"""

